/// Builds the database `sql` describes at `path`, on a plain connection.
///
/// # Panics
///
/// Panics when the database cannot be built, which is a fault of the fixture.
fn from_text(path: &Path, sql: &str, writable_schema: bool) {
    let connection = Connection::open(path).expect("the fixture database opens");
    if writable_schema {
        // Defensive mode refuses PRAGMA writable_schema=ON; this connection
        // is the builder's own, and only it sets the mode off (OD-37).
        connection
            .set_db_config(DbConfig::SQLITE_DBCONFIG_DEFENSIVE, false)
            .expect("the builder sets defensive mode off");
        assert!(
            !connection
                .db_config(DbConfig::SQLITE_DBCONFIG_DEFENSIVE)
                .expect("defensive mode reads back"),
            "the builder's defensive mode is off"
        );
    }
    connection
        .execute_batch(sql)
        .unwrap_or_else(|failure| panic!("{} builds: {failure}", path.display()));
    connection.close().expect("the fixture database closes");
}

/// Builds, at `path`, the shape of the security review's `poc_dos`: a table
/// of `columns` columns, and `depth` views each selecting twice from the one
/// before, the first from the table — generated by a rule, as the oversized
/// statement is (`OD-37`).
///
/// # Panics
///
/// Panics when the database cannot be built.
pub fn nested_views(path: &Path, columns: usize, depth: usize) {
    let mut sql = String::from("BEGIN;\nCREATE TABLE manifest_line (");
    sql.push_str(
        &(0..columns)
            .map(|at| format!("field_{at}"))
            .collect::<Vec<_>>()
            .join(", "),
    );
    sql.push_str(");\nCREATE VIEW v0 AS SELECT * FROM manifest_line;\n");
    for level in 1..=depth {
        let below = level - 1;
        sql.push_str(&format!(
            "CREATE VIEW v{level} AS SELECT * FROM v{below} UNION ALL SELECT * FROM v{below};\n"
        ));
    }
    sql.push_str("COMMIT;\n");
    from_text(path, &sql, false);
}

/// Builds, at `path`, the shape of the security review's `many_N`: one table
/// and `count` views of the form `SELECT 1` — generated by a rule (`OD-37`).
///
/// # Panics
///
/// Panics when the database cannot be built.
pub fn many_views(path: &Path, count: usize) {
    let mut sql = String::from("BEGIN;\nCREATE TABLE port (port_code TEXT PRIMARY KEY);\n");
    for at in 0..count {
        sql.push_str(&format!("CREATE VIEW v{at:07} AS SELECT 1;\n"));
    }
    sql.push_str("COMMIT;\n");
    from_text(path, &sql, false);
}

/// Builds the main database alone at `path`.
///
/// # Panics
///
/// Panics when the database cannot be built, which is a fault of the fixture.
pub fn main_database(path: &Path) {
    let connection = Connection::open(path).expect("the fixture database opens");
    connection
        .execute_batch(FREIGHT)
        .expect("scripts/sqlite/freight.sql builds");
    connection.close().expect("the fixture database closes");
}

/// Builds every artefact under `root`, which must exist and be empty.
///
/// # Panics
///
/// Panics when an artefact cannot be built.
pub fn build(root: &Path) -> Artefacts {
    let main = root.join("freight.sqlite");
    main_database(&main);

    let wal_directory = root.join("wal");
    std::fs::create_dir_all(&wal_directory).expect("the root is writable");
    let wal = wal_directory.join("freight-wal.sqlite");
    std::fs::copy(&main, &wal).expect("the main database copies");
    {
        let connection = Connection::open(&wal).expect("the copy opens");
        let mode: String = connection
            .query_row("PRAGMA journal_mode = WAL", [], |row| row.get(0))
            .expect("the copy switches to write-ahead-log mode");
        assert_eq!(mode, "wal");
        connection.close().expect("the copy closes");
    }
    // The connection that switched the mode leaves no -wal or -shm behind
    // when it closes cleanly; the read under test is what may create them.
    for suffix in ["-wal", "-shm"] {
        let _ = std::fs::remove_file(PathBuf::from(format!("{}{suffix}", wal.display())));
    }

    let empty = root.join("empty.sqlite");
    std::fs::write(&empty, b"").expect("the root is writable");

    let text = root.join("manifest.txt");
    std::fs::write(
        &text,
        "Consignment BKG-2026-40211: 22 pallets of Rocha pears, reefer at 4 C.\n",
    )
    .expect("the root is writable");

    let truncated = root.join("truncated.sqlite");
    let bytes = std::fs::read(&main).expect("the main database reads");
    std::fs::write(&truncated, &bytes[..100]).expect("the root is writable");

    let directory = root.join("a-directory.sqlite");
    std::fs::create_dir_all(&directory).expect("the root is writable");

    let fifo = root.join("a-fifo.sqlite");
    let made = Command::new("mkfifo")
        .arg(&fifo)
        .status()
        .expect("mkfifo runs");
    assert!(made.success(), "mkfifo {} failed", fifo.display());

    let link = root.join("link.sqlite");
    std::os::unix::fs::symlink(&main, &link).expect("the link is made");

    let dangling = root.join("dangling.sqlite");
    std::os::unix::fs::symlink(root.join("nothing-here.sqlite"), &dangling)
        .expect("the dangling link is made");

    let oversized = root.join("oversized.sqlite");
    {
        let connection = Connection::open(&oversized).expect("the database opens");
        let statement = format!(
            "CREATE TABLE customs_declaration (declaration_id INTEGER PRIMARY KEY, boilerplate TEXT \
             DEFAULT '{}')",
            "x".repeat(OVERSIZED)
        );
        connection
            .execute_batch(&statement)
            .expect("a connection without the limit writes the statement");
        connection.close().expect("the database closes");
    }

    let internal = root.join("internal.sqlite");
    {
        let connection = Connection::open(&internal).expect("the database opens");
        connection
            .execute_batch(INTERNAL)
            .expect("scripts/sqlite/internal.sql builds");
        connection.close().expect("the database closes");
    }

    let built = |name: &str, sql: &str, writable_schema: bool| {
        let path = root.join(name);
        from_text(&path, sql, writable_schema);
        path
    };
    let pragma_view = built("pragma-view.sqlite", PRAGMA_VIEW, false);
    let pragma_table = built("pragma-table.sqlite", PRAGMA_TABLE, false);
    let blob_view_sql = built("blob-view-sql.sqlite", BLOB_VIEW_SQL, true);
    let blob_trigger_type = built("blob-trigger-type.sqlite", BLOB_TRIGGER_TYPE, true);
    let rootpage_zero = built("rootpage-zero.sqlite", ROOTPAGE_ZERO, true);
    let rootpage_virtual = built("rootpage-virtual.sqlite", ROOTPAGE_VIRTUAL, true);
    let fts5 = built("fts5-view.sqlite", FTS5_VIEW, false);
    let type_upper_pragma = built("type-upper-pragma.sqlite", TYPE_UPPER_PRAGMA, true);
    let type_title_case = built("type-title-case.sqlite", TYPE_TITLE_CASE, true);
    let type_nul_trigger = built("type-nul-trigger.sqlite", TYPE_NUL_TRIGGER, true);
    let no_text_table = built("no-text-table.sqlite", NO_TEXT_TABLE, true);
    let empty_text_view = built("empty-text-view.sqlite", EMPTY_TEXT_VIEW, true);
    let nul_trigger_table = built("nul-trigger-table.sqlite", NUL_TRIGGER_TABLE, true);
    let nul_view_sql = built("nul-view-sql.sqlite", NUL_VIEW_SQL, true);
    let temp_trigger = built("temp-trigger.sqlite", TEMP_TRIGGER, true);
    let alike_tables = built("alike-tables.sqlite", ALIKE_TABLES, true);
    let alike_columns = built("alike-columns.sqlite", ALIKE_COLUMNS, true);
    let alike_dangling_key = built("alike-dangling-key.sqlite", ALIKE_DANGLING_KEY, true);

    Artefacts {
        root: root.to_owned(),
        main,
        wal,
        empty,
        text,
        truncated,
        directory,
        fifo,
        link,
        dangling,
        oversized,
        internal,
        pragma_view,
        pragma_table,
        blob_view_sql,
        blob_trigger_type,
        rootpage_zero,
        rootpage_virtual,
        fts5,
        type_upper_pragma,
        type_title_case,
        type_nul_trigger,
        no_text_table,
        empty_text_view,
        nul_trigger_table,
        nul_view_sql,
        temp_trigger,
        alike_tables,
        alike_columns,
        alike_dangling_key,
    }
}
