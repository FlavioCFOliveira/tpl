//! The SQLite fixture of `FR-LITE-038`, built at test time from the SQL text
//! of `scripts/sqlite/` (`OD-37`).
//!
//! Every artefact is built into a directory the caller owns and removes,
//! through `rusqlite` — the library the binary carries — on a plain connection
//! with none of `tpl`'s controls: item 9 of `FR-LITE-038` is written under
//! `trusted_schema` on, and the length-limit database by a connection that
//! does not set the limit. No binary database file is committed.
//!
//! | Artefact | Built from |
//! |---|---|
//! | The main database, items 1 to 13 | `scripts/sqlite/freight.sql` |
//! | A copy in write-ahead-log mode | The main database, copied and switched with `journal_mode` |
//! | An empty file, a text file, a truncated database | Bytes written here |
//! | A directory, a FIFO, a link to the main database, a dangling link | The filesystem; the FIFO with the system's `mkfifo` |
//! | A schema statement longer than the length limit of `FR-LITE-011` | A `CREATE TABLE` generated by a rule |
//! | A database whose only objects are the internal tables | `scripts/sqlite/internal.sql` |
//!
//! # Why this file is under `tests/support/` and is reached by `#[path]`
//!
//! For the reason `tests/support/fixture.rs` states: it is compiled into every
//! binary that names it — the library's unit tests and the integration targets
//! — and is never a test target of its own.

#![allow(
    dead_code,
    reason = "this module is included by more than one test binary and each uses the \
              artefacts its own subject needs; an item unused in one of them is not dead code"
)]

use std::path::{Path, PathBuf};
use std::process::Command;

use rusqlite::Connection;

/// The main database's SQL text.
const FREIGHT: &str = include_str!("../../scripts/sqlite/freight.sql");

/// The internal-tables database's SQL text.
const INTERNAL: &str = include_str!("../../scripts/sqlite/internal.sql");

/// The length of the oversized `CREATE TABLE` statement, past the million
/// bytes of `FR-LITE-011`.
const OVERSIZED: usize = 1_100_000;

/// Every artefact `FR-LITE-038` lists, built under one directory.
#[derive(Debug)]
pub struct Artefacts {
    /// The directory they are built in.
    pub root: PathBuf,
    /// The main database, in rollback-journal mode.
    pub main: PathBuf,
    /// A copy of it in write-ahead-log mode, in a directory of its own.
    pub wal: PathBuf,
    /// An empty file of zero bytes.
    pub empty: PathBuf,
    /// A text file.
    pub text: PathBuf,
    /// The main database cut to its first 100 bytes.
    pub truncated: PathBuf,
    /// A directory.
    pub directory: PathBuf,
    /// A FIFO.
    pub fifo: PathBuf,
    /// A symbolic link to the main database.
    pub link: PathBuf,
    /// A symbolic link to nothing.
    pub dangling: PathBuf,
    /// A database whose schema holds a statement longer than the length limit.
    pub oversized: PathBuf,
    /// A database whose only objects are the internal tables.
    pub internal: PathBuf,
}

/// Builds the main database alone at `path`.
///
/// # Panics
///
/// Panics when the database cannot be built, which is a fault of the fixture.
pub fn main_database(path: &Path) {
    let connection = Connection::open(path).expect("the fixture database opens");
    connection
        .execute_batch(FREIGHT)
        .expect("scripts/sqlite/freight.sql builds");
    connection.close().expect("the fixture database closes");
}

/// Builds every artefact under `root`, which must exist and be empty.
///
/// # Panics
///
/// Panics when an artefact cannot be built.
pub fn build(root: &Path) -> Artefacts {
    let main = root.join("freight.sqlite");
    main_database(&main);

    let wal_directory = root.join("wal");
    std::fs::create_dir_all(&wal_directory).expect("the root is writable");
    let wal = wal_directory.join("freight-wal.sqlite");
    std::fs::copy(&main, &wal).expect("the main database copies");
    {
        let connection = Connection::open(&wal).expect("the copy opens");
        let mode: String = connection
            .query_row("PRAGMA journal_mode = WAL", [], |row| row.get(0))
            .expect("the copy switches to write-ahead-log mode");
        assert_eq!(mode, "wal");
        connection.close().expect("the copy closes");
    }
    // The connection that switched the mode leaves no -wal or -shm behind
    // when it closes cleanly; the read under test is what may create them.
    for suffix in ["-wal", "-shm"] {
        let _ = std::fs::remove_file(PathBuf::from(format!("{}{suffix}", wal.display())));
    }

    let empty = root.join("empty.sqlite");
    std::fs::write(&empty, b"").expect("the root is writable");

    let text = root.join("manifest.txt");
    std::fs::write(
        &text,
        "Consignment BKG-2026-40211: 22 pallets of Rocha pears, reefer at 4 C.\n",
    )
    .expect("the root is writable");

    let truncated = root.join("truncated.sqlite");
    let bytes = std::fs::read(&main).expect("the main database reads");
    std::fs::write(&truncated, &bytes[..100]).expect("the root is writable");

    let directory = root.join("a-directory.sqlite");
    std::fs::create_dir_all(&directory).expect("the root is writable");

    let fifo = root.join("a-fifo.sqlite");
    let made = Command::new("mkfifo")
        .arg(&fifo)
        .status()
        .expect("mkfifo runs");
    assert!(made.success(), "mkfifo {} failed", fifo.display());

    let link = root.join("link.sqlite");
    std::os::unix::fs::symlink(&main, &link).expect("the link is made");

    let dangling = root.join("dangling.sqlite");
    std::os::unix::fs::symlink(root.join("nothing-here.sqlite"), &dangling)
        .expect("the dangling link is made");

    let oversized = root.join("oversized.sqlite");
    {
        let connection = Connection::open(&oversized).expect("the database opens");
        let statement = format!(
            "CREATE TABLE customs_declaration (declaration_id INTEGER PRIMARY KEY, boilerplate TEXT \
             DEFAULT '{}')",
            "x".repeat(OVERSIZED)
        );
        connection
            .execute_batch(&statement)
            .expect("a connection without the limit writes the statement");
        connection.close().expect("the database closes");
    }

    let internal = root.join("internal.sqlite");
    {
        let connection = Connection::open(&internal).expect("the database opens");
        connection
            .execute_batch(INTERNAL)
            .expect("scripts/sqlite/internal.sql builds");
        connection.close().expect("the database closes");
    }

    Artefacts {
        root: root.to_owned(),
        main,
        wal,
        empty,
        text,
        truncated,
        directory,
        fifo,
        link,
        dangling,
        oversized,
        internal,
    }
}
